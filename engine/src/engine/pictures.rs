//! Automatic before and after pictures of local app pages already known when a project answer is admitted.
use super::*;
use crate::browser;
use sha2::{Digest, Sha256};
use std::io::{self, Write};

const MAX_PAGES: usize = 3;
const RECENT_MESSAGES: usize = 40;
const CAPTURE_TIMEOUT: Duration = Duration::from_secs(8);

pub(super) struct TurnPictures {
    pages: Vec<String>,
    before: PictureTask,
}

pub(super) struct PictureTask(tokio::task::AbortHandle);

impl Drop for PictureTask {
    fn drop(&mut self) {
        self.0.abort();
    }
}

#[derive(Clone, Copy)]
enum Phase {
    Before,
    After,
}

/// In `attachments/<conversation>/answer-pictures/pictures-<answer-message-id>.json`, positions match the one-based
/// page numbers in `before-<answer-message-id>-<n>.jpg` and `after-<answer-message-id>-<n>.jpg`. Each entry has
/// nullable `before` and `after` filenames, and a URL digest so a retry cannot pair pictures of different pages.
/// Missing captures are null. No URLs or page text are stored here.
#[derive(Default, serde::Deserialize, serde::Serialize)]
struct Pair {
    page: Option<String>,
    before: Option<String>,
    after: Option<String>,
}

fn pages(c: &Conversation, blocked: &[String]) -> Vec<String> {
    let tabs = c.browser.iter().flat_map(|tabs| tabs.front_tab().into_iter().chain(tabs.tabs.iter()));
    let announced = c
        .messages
        .iter()
        .rev()
        .take(RECENT_MESSAGES)
        .flat_map(|m| m.tools.iter().flatten().rev())
        .filter(|t| t.parent.is_none() && !t.declined && crate::stuck::is_command(&t.name))
        .filter_map(|t| t.output.as_deref())
        .flat_map(browser::announced_apps);
    let mut pages = Vec::new();
    let mut origins = HashSet::new();
    for (from_tab, mut url) in
        tabs.filter_map(|tab| browser::local_app_url(&tab.url).map(|url| (true, url))).chain(announced.map(|url| (false, url)))
    {
        if browser::check_blocked_url(url.as_str(), blocked).is_err() || (!from_tab && origins.contains(&url.origin())) {
            continue;
        }
        url.set_fragment(None);
        origins.insert(url.origin());
        let url = url.to_string();
        if !pages.contains(&url) {
            pages.push(url);
        }
        if pages.len() == MAX_PAGES {
            break;
        }
    }
    pages
}

impl Core {
    pub(super) fn start_answer_pictures(&self, conv: &str, message: &str) -> Option<TurnPictures> {
        if self.closing || self.browser.is_none() {
            return None;
        }
        let c = self.convs.get(conv).filter(|c| c.area == Area::Project && !c.temporary)?;
        let pages = pages(c, self.store.settings().blocked_hosts.as_deref().unwrap_or_default());
        if pages.is_empty() {
            return None;
        }
        let before = self.capture_answer_pictures(conv, message, pages.clone(), Phase::Before)?;
        Some(TurnPictures { pages, before: PictureTask(before) })
    }

    pub(super) fn finish_answer_pictures(&mut self, conv: &str) {
        if self.closing {
            return;
        }
        let live = self.live.get(conv).and_then(|live| live.turn.as_deref());
        let Some(heard) = self.heard.get_mut(conv).filter(|heard| Some(heard.turn.as_str()) != live) else { return };
        let Some(TurnPictures { pages, before }) = heard.pictures.take() else { return };
        let message = heard.turn.clone();
        drop(before); // Keep the JPEGs already captured, and stop waiting for the rest of the before set.
        self.after_pictures.retain(|_, task| !task.0.is_finished());
        if let Some(after) = self.capture_answer_pictures(conv, &message, pages, Phase::After) {
            self.after_pictures.insert(conv.to_string(), PictureTask(after));
        }
    }

    fn capture_answer_pictures(&self, conv: &str, message: &str, pages: Vec<String>, phase: Phase) -> Option<tokio::task::AbortHandle> {
        let browser = self.browser.clone()?;
        // Message ids are generated by Faber. Reject an imported id that could address anything outside this attachment folder.
        if !safe_message(message) {
            return None;
        }
        let dir = self.opts.data_dir.join("attachments").join(conv);
        let (me, conv, message) = (self.me.clone(), conv.to_string(), message.to_string());
        let task = self.opts.runtime.spawn(async move {
            let budget_dir = dir.clone();
            if !tokio::task::spawn_blocking(move || browser::picture_room(&budget_dir, "", 1, browser::MAX_PICTURES_BYTES, false))
                .await
                .is_ok_and(|room| room.unwrap_or(false))
            {
                return;
            }
            for (n, url) in pages.into_iter().enumerate() {
                let Ok(Some(jpeg)) = tokio::time::timeout(CAPTURE_TIMEOUT, browser.capture_local(url.clone())).await else { continue };
                let (me, dir, conv, message) = (me.clone(), dir.clone(), conv.clone(), message.clone());
                let _ = tokio::task::spawn_blocking(move || {
                    let Some(core) = me.upgrade() else { return };
                    let core = core.lock().unwrap_or_else(|e| e.into_inner());
                    // Serialize with deletion and manual captures. A capture already finished at turn end may still be saved.
                    if !core.closing && (core.convs.contains_key(&conv) || core.store.get(&conv).is_some()) {
                        let _ = keep(&dir, &message, phase, n, &url, &jpeg);
                    }
                })
                .await;
            }
        });
        Some(task.abort_handle())
    }
}

fn keep(dir: &Path, message: &str, phase: Phase, n: usize, url: &str, jpeg: &[u8]) -> io::Result<()> {
    let answers = dir.join(browser::ANSWER_PICTURES_DIR);
    let path = answers.join(format!("pictures-{message}.json"));
    let mut pairs: Vec<Pair> = match std::fs::File::open(&path) {
        Ok(file) => serde_json::from_reader(file)?,
        Err(e) if e.kind() == io::ErrorKind::NotFound => Vec::new(),
        Err(e) => return Err(e),
    };
    if pairs.len() <= n {
        pairs.resize_with(n + 1, Pair::default);
    }
    let pair = &mut pairs[n];
    let page = crate::hex(&Sha256::digest(url.as_bytes()));
    if pair.page.as_ref().is_some_and(|previous| previous != &page) {
        return Ok(());
    }
    pair.page = Some(page);
    let (prefix, slot) = match phase {
        Phase::Before => ("before", &mut pair.before),
        Phase::After => ("after", &mut pair.after),
    };
    if slot.is_some() {
        return Ok(());
    }
    let name = format!("{prefix}-{message}-{}.jpg", n + 1);
    if !browse::keep_picture(dir, &name, jpeg, false)? {
        return Ok(());
    }
    *slot = Some(name.clone());
    let recorded = (|| -> io::Result<()> {
        let mut record = tempfile::NamedTempFile::new_in(&answers)?;
        record.write_all(&serde_json::to_vec(&pairs)?)?;
        record.persist(&path)?;
        Ok(())
    })();
    if recorded.is_err() {
        let _ = std::fs::remove_file(answers.join(name));
    }
    recorded
}

fn safe_message(message: &str) -> bool {
    !message.is_empty() && message.len() <= 80 && message.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_'))
}

/// One page of an answer's before and after pictures, as the screen shows it: the one-based page number and the names of the
/// pictures kept in the answer's folder (`site_picture` reads them). A picture that was not taken, or is gone, is none.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct AnswerPage {
    pub page: usize,
    pub before: Option<String>,
    pub after: Option<String>,
}

/// The most a record may weigh, checked before it is read: three pages take well under a kilobyte.
const MAX_RECORD_BYTES: u64 = 64 * 1024;
/// The most records one read of a conversation looks at: its newest answers.
const MAX_RECORDS: usize = 500;

/// The metadata of a plain file (or, with `folder`, a plain folder) at `path`, read without following it: a symbolic
/// link or a junction is refused, so nothing read here can lead outside the conversation's attachments.
fn plain(path: &Path, folder: bool) -> Option<std::fs::Metadata> {
    let meta = std::fs::symlink_metadata(path).ok()?;
    (if folder { meta.is_dir() } else { meta.is_file() }).then_some(meta)
}

/// The pages of answer `message` whose record sits in `answers` (the answers' folder) that kept at least one picture, in
/// page order. Only the exact names `keep` writes are given back, so a changed record can never name another file.
fn answer_pages(answers: &Path, message: &str) -> Vec<AnswerPage> {
    use std::io::Read as _;
    let path = answers.join(format!("pictures-{message}.json"));
    if !safe_message(message) || !plain(&path, false).is_some_and(|meta| meta.len() <= MAX_RECORD_BYTES) {
        return Vec::new();
    }
    let mut record = Vec::new();
    let Ok(file) = std::fs::File::open(&path) else { return Vec::new() };
    if file.take(MAX_RECORD_BYTES + 1).read_to_end(&mut record).is_err() || record.len() as u64 > MAX_RECORD_BYTES {
        return Vec::new();
    }
    let Ok(pairs) = serde_json::from_slice::<Vec<Pair>>(&record) else { return Vec::new() };
    let kept = |prefix: &str, n: usize, name: Option<String>| {
        name.filter(|name| *name == format!("{prefix}-{message}-{n}.jpg") && plain(&answers.join(name), false).is_some())
    };
    pairs
        .into_iter()
        .take(MAX_PAGES)
        .enumerate()
        .map(|(i, pair)| AnswerPage { page: i + 1, before: kept("before", i + 1, pair.before), after: kept("after", i + 1, pair.after) })
        .filter(|page| page.before.is_some() || page.after.is_some())
        .collect()
}

/// Every answer of a conversation whose record in `dir` (its attachments) kept at least one picture, by message id: the
/// answers' folder is listed once, and the newest `MAX_RECORDS` plain records are read with the rules of `answer_pages`.
pub(super) fn answers_pages(dir: &Path) -> BTreeMap<String, Vec<AnswerPage>> {
    let answers = dir.join(browser::ANSWER_PICTURES_DIR);
    if plain(dir, true).is_none() || plain(&answers, true).is_none() {
        return BTreeMap::new();
    }
    let Ok(entries) = std::fs::read_dir(&answers) else { return BTreeMap::new() };
    // A listed entry's metadata is its own, never what a link points at.
    let mut records: Vec<(SystemTime, String)> = entries
        .filter_map(|entry| {
            let entry = entry.ok()?;
            let message = entry.file_name().to_str()?.strip_prefix("pictures-")?.strip_suffix(".json")?.to_string();
            let meta = entry.metadata().ok()?;
            (safe_message(&message) && meta.is_file() && meta.len() <= MAX_RECORD_BYTES)
                .then(|| (meta.modified().unwrap_or(UNIX_EPOCH), message))
        })
        .collect();
    records.sort_unstable_by(|a, b| b.cmp(a));
    records.truncate(MAX_RECORDS);
    records
        .into_iter()
        .filter_map(|(_, message)| {
            let pages = answer_pages(&answers, &message);
            (!pages.is_empty()).then_some((message, pages))
        })
        .collect()
}

/// Where the picture `call` names is kept in `dir` (a conversation's attachments): a browser call's picture, or an answer's
/// before or after picture by its file name. Every folder and the file itself must be plain, never a link.
pub(super) fn picture_path(dir: &Path, call: &str) -> Option<PathBuf> {
    if !is_answer_picture(call) {
        return tool_picture_path(dir, call, true);
    }
    plain(dir, true)?;
    let answers = dir.join(browser::ANSWER_PICTURES_DIR);
    plain(&answers, true)?;
    let path = answers.join(call);
    plain(&path, false)?;
    Some(path)
}

pub(super) fn tool_picture_path(dir: &Path, call: &str, legacy_aliases: bool) -> Option<PathBuf> {
    plain(dir, true)?;
    browser::picture_file(dir, call, legacy_aliases)
}

/// Whether `name` is one of the pictures `keep` writes, so `site_picture` looks for it in the answers' folder.
pub(super) fn is_answer_picture(name: &str) -> bool {
    name.strip_suffix(".jpg")
        .and_then(|stem| stem.strip_prefix("before-").or_else(|| stem.strip_prefix("after-")))
        .is_some_and(|rest| rest.len() <= 90 && rest.contains('-') && safe_message(rest))
}

