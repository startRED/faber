    struct FakeBrowser {
        calls: Mutex<Vec<String>>,
        count: AtomicUsize,
        hold: Option<usize>,
        started: tokio::sync::Notify,
        cancelled: Arc<tokio::sync::Notify>,
    }

    struct PendingCapture(Arc<tokio::sync::Notify>);

    impl Drop for PendingCapture {
        fn drop(&mut self) {
            self.0.notify_one();
        }
    }

    impl browser::Browser for FakeBrowser {
        fn act(&self, _: String, _: String, _: browser::Request) -> Pin<Box<dyn Future<Output = Result<browser::Page, String>> + Send>> {
            panic!("automatic pictures must not operate the person's or the agent's tab");
        }

        fn capture_local(&self, url: String) -> Pin<Box<dyn Future<Output = Option<Vec<u8>>> + Send>> {
            self.calls.lock().unwrap().push(url);
            let n = self.count.fetch_add(1, Ordering::Relaxed);
            self.started.notify_one();
            if self.hold == Some(n) {
                let pending = PendingCapture(self.cancelled.clone());
                return Box::pin(async move {
                    let _pending = pending;
                    std::future::pending().await
                });
            }
            Box::pin(async move { Some(vec![n as u8]) })
        }
    }

